import os, random, re
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))

GAP = 6.0            # pt between blocks, matches \nbgap / \nbfix
SLACK = 2.0          # pt kept free in every column
FIRST = ["legend", "template", "bwin", "b", "stresswin", "stress",
         "gen", "check", "templatepy"]   # opening columns, in order
WIDE = ["point", "orderedset", "halfplane", "circle", "point3d",
        "simplex"]                       # full-width pages at the end
WITH = {"orderedset": "point"}           # goes on the same wide page
ORDER = ["contest", "ds", "nt", "comb", "alg", "graph", "string",
         "geo", "dp", "misc"]

def pt(s): return float(s.replace("pt", ""))

h, hw, H = {}, {}, None
for line in open("build/heights.txt"):
    k, a, b = line.split()
    if k == "TEXTHEIGHT": H = pt(a)
    else: h[k], hw[k] = pt(a), pt(b)
mat = {}
for m in re.finditer(r"\\def(?:code|plain|text)\{([^}]*)\}\{([^}]*)\}",
                     open("blocks.tex").read()):
    mat[m.group(1)] = m.group(2)
CAP = H - SLACK

def load(col, hh=h): return sum(hh[i] for i in col) + GAP * (len(col) - 1)

def fits(col, i): return load(col + [i]) <= CAP

def pack(items, cols=None, tries=300, seed=1):
    rnd = random.Random(seed)
    best = None
    for t in range(tries):
        order = sorted(items, key=lambda i: -h[i])
        if t:
            order = sorted(items, key=lambda i: -h[i] * rnd.uniform(.85, 1))
        res = [list(c) for c in (cols or [])]
        for i in order:
            cand = [c for c in res if fits(c, i)]
            if cand:
                min(cand, key=lambda c: CAP - load(c + [i])).append(i)
            else:
                res.append([i])
        key = (len(res), -max((CAP - load(c) for c in res), default=0))
        if best is None or key < best[0]:
            best = (key, res)
    return best[1]

for i in h:
    assert (hw if i in WIDE else h)[i] <= CAP, "block %s too tall" % i

# opening columns: contest material in a fixed reading order
head = []
for i in FIRST:
    if head and fits(head[-1], i): head[-1].append(i)
    else: head.append([i])
nhead = len(head)
free = [i for i in h if i not in FIRST and i not in WIDE]

# full-width pages: wide blocks first-fit decreasing, partners attached
wide = []
for i in sorted([w for w in WIDE if w not in WITH], key=lambda i: -hw[i]):
    for c in wide:
        if load(c + [i], hw) <= CAP: c.append(i); break
    else: wide.append([i])
for f, a in WITH.items():
    c = next(c for c in wide if a in c)
    assert load(c + [f], hw) <= CAP, "%s does not fit with %s" % (f, a)
    c.append(f)

def twocol(free):
    # material-coherent packing: full columns per material, then the rest
    full, rest = [], []
    for m in ORDER:
        cols = pack([i for i in free if mat[i] == m], tries=100)
        for c in cols:
            if load(c) >= 0.93 * CAP: full.append(c)
            else: rest += c
    coherent = pack(rest, head + full)
    mixed = pack(free, head)
    return coherent if len(coherent) <= len(mixed) else mixed

# fill the wide pages with blocks from the partial two-column tail
cols = twocol(free)
while True:
    tail = [i for c in cols[nhead:] if load(c) < 0.9 * CAP for i in c]
    moved = False
    for i in sorted(tail, key=lambda i: -hw[i]):
        cand = [c for c in wide if load(c + [i], hw) <= CAP]
        if cand:
            min(cand, key=lambda c: CAP - load(c + [i], hw)).append(i)
            free.remove(i)
            moved = True
    if not moved: break
    cols = twocol(free)
print("two-column: %d columns, wide pages: %d" % (len(cols), len(wide)))

def dom(c):
    w = {}
    for i in c: w[mat[i]] = w.get(mat[i], 0) + h[i]
    return max(w, key=w.get)

def key(i): return (ORDER.index(mat[i]), -h[i])

opening = []
for c in cols[:nhead]:
    opening.append([i for i in FIRST if i in c] +
                   sorted([i for i in c if i not in FIRST], key=key))
tail = cols[nhead:]
tail.sort(key=lambda c: (load(c) < 0.9 * CAP, ORDER.index(dom(c))))
cols = opening + [sorted(c, key=key) for c in tail]
if len(cols) % 2: cols.append([])

wide.sort(key=lambda c: WIDE.index(min(
    (i for i in c if i in WIDE), key=WIDE.index)))
wide = [[i for i in WIDE if i in c] + sorted(
    [i for i in c if i not in WIDE], key=key) for c in wide]

def sep(c, hh=h):
    return "\\nbgap" if c and load(c, hh) >= 0.9 * CAP else "\\nbfix"

def body(c, hh=h):
    return ("%\n" + sep(c, hh) + "\n").join("\\nbblk{%s}" % i for i in c)

out = ["% generated by tools/pack.py, do not edit"]
for p in range(0, len(cols), 2):
    out.append("\\nbpage{%%\n%s}{%%\n%s}" % (body(cols[p]), body(cols[p + 1])))
for c in wide:
    out.append("\\nbwide{%%\n%s}" % body(c, hw))
open("layout.tex", "w", newline="\n").write("\n".join(out) + "\n")
for k, c in enumerate(cols):
    print("col %2d  %5.1f%%  %s" % (k + 1, 100 * load(c) / CAP if c else 0,
                                   " ".join(c)))
for c in wide:
    print("wide    %5.1f%%  %s" % (100 * load(c, hw) / CAP, " ".join(c)))
print("pages:", len(cols) // 2 + len(wide))
